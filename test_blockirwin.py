def _check(refs, label):
    bad = 0
    for b, w, k, ref in refs:
        nd = len(ref.replace(".", "").lstrip("0"))
        got = blockirwin(b, w, k, nd)
        mp.dps = nd + 10
        ulp = mpf(10) ** (-(len(ref) - ref.index(".") - 1))
        ok = abs(mpf(got) - mpf(ref)) <= ulp * mpf("1.01")
        bad += not ok
        if not ok:
            print(f"  MISMATCH I({b},\"{w}\",{k}): ref={ref} got={got}")
    print(f"{label}: {bad} mismatch(es) out of {len(refs)}")
    return bad


def test_levels(nd=120):
    cases = [(2, "101", 2, (6, 9, 13)), (2, "1111", 3, (6, 9, 13)),
             (2, "0110", 1, (6, 9, 13)), (3, "1212", 2, (3, 5, 7)),
             (10, "999", 2, (2, 3, 4)), (10, "010", 1, (2, 3, 4)),
             (16, "abab", 2, (2, 3)), (16, "f0f", 1, (2, 3))]
    bad = 0
    for b, w, k, ells in cases:
        mp.dps = nd + 10
        vals = [mpf(blockirwin(b, w, k, nd, ell=e)) for e in ells]
        ok = max(vals) - min(vals) <= abs(vals[0]) * mpf(10) ** (1 - nd)
        bad += not ok
        if not ok:
            print(f"  MISMATCH levels b={b} w={w} k={k}: {vals}")
    print(f"level independence: {bad} mismatch(es) out of {len(cases)}")
    return bad


def _lambda(b, w, j):
    w = _parse_block(b, w)
    p = len(w)
    t = Fraction(1, b**j)
    C = 1 + sum(t**h for h in _overlap_periods(w))
    D = (1 - b * t) * C + t**p
    E = (1 - b * t) * (C - 1) + t**p
    return E / D


def test_modal(nd=100):
    bad = 0
    cases = [(2, "101"), (2, "1111"), (2, "000"), (3, "1212")]
    for b, w in cases:
        p = len(w)
        mp.dps = nd + 10
        L = b**p * log(b)
        I1 = mpf(blockirwin(b, w, 20, nd))
        I2 = mpf(blockirwin(b, w, 21, nd))
        lam2, lam3 = _lambda(b, w, 2), _lambda(b, w, 3)
        ratio = (I2 - L) / (I1 - L)
        expected = mpf(lam2.numerator) / lam2.denominator
        tol = 10 * (mpf(lam3.numerator) * lam2.denominator
                    / (lam3.denominator * lam2.numerator)) ** 20
        ok = abs(ratio / expected - 1) < tol
        bad += not ok
        if not ok:
            print(f"  MISMATCH modal b={b} w={w}: ratio={nstr(ratio,12)}"
                  f" expected={nstr(expected,12)}")
    print(f"modal decay rate: {bad} mismatch(es) out of {len(cases)}")
    return bad


